"""Datasets over precomputed ESP tensor caches, for SSL pretraining.

Both pretext tasks read the same on-disk layout produced by
``scripts/build_esp_dataset.py``: one subdirectory per structure, containing
its rotation-augmented ``*.npy`` arrays (shape ``(grid_dim,)*3``, e.g. 96^3).
Multiple cache roots (e.g. the SabDab and OAS/IgFold builds) can be combined,
since each pretext task only needs the per-structure file groups, not any
particular directory naming convention.
"""
from typing import List, Union, Sequence
from pathlib import Path
from torch.utils.data import Dataset

import numpy as np
import torch
import random


def list_structure_npy_groups(roots: Sequence[Union[str, Path]]) -> List[List[Path]]:
    """Discover structure subdirectories across one or more artefact roots.

    Returns one entry per structure: the sorted list of its rotation ``.npy``
    files. Roots that don't exist are skipped (useful when combining a
    still-building cache with a finished one).
    """
    groups = []
    for root in roots:
        root = Path(root)
        if not root.is_dir():
            continue
        for d in sorted(root.iterdir()):
            if not d.is_dir():
                continue
            npy_files = sorted(d.glob('*.npy'))
            if npy_files:
                groups.append(npy_files)
    return groups


def _load(path: Path) -> torch.Tensor:
    arr = np.load(path).astype(np.float32)
    return torch.from_numpy(arr).unsqueeze(0)  # (1, D, H, W)


class VICRegPretrainDataset(Dataset):
    """Yields two independently-rotated ESP views of the same structure.

    VICReg's invariance term needs two "views" of one underlying antibody;
    the rotation augmentations already generated by the APBS pipeline serve
    that role directly (same molecule, different orientation/APBS solve), so
    no additional data augmentation is applied here.
    """

    def __init__(self, roots: Sequence[Union[str, Path]], min_views: int = 2):
        groups = list_structure_npy_groups(roots)
        self.groups = [g for g in groups if len(g) >= min_views]
        skipped = len(groups) - len(self.groups)
        if skipped:
            import logging

            logging.getLogger(__name__).warning(
                f'{skipped} structures had fewer than {min_views} rotation views and were skipped'
            )

    def __len__(self):
        return len(self.groups)

    def __getitem__(self, idx):
        files = self.groups[idx]
        i, j = random.sample(range(len(files)), 2)
        return _load(files[i]), _load(files[j])


class MAEPretrainDataset(Dataset):
    """Flattens every rotation view across every structure into one MAE sample.

    Unlike VICReg, masked-reconstruction doesn't need paired views - each
    rotation is an independent training example.
    """

    def __init__(self, roots: Sequence[Union[str, Path]]):
        self.files = [f for g in list_structure_npy_groups(roots) for f in g]

    def __len__(self):
        return len(self.files)

    def __getitem__(self, idx):
        return _load(self.files[idx])
